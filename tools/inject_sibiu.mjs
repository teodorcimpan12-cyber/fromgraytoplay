// Replaces the COURTS_SIBIU array and CITY_CFG.sibiu.hoods in index.html from tools/data/courts_sibiu.json.
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const file = new URL("index.html", root);
const data = JSON.parse(readFileSync(new URL("tools/data/courts_sibiu.json", root), "utf8"));
let html = readFileSync(file, "utf8");

// A court becomes "verified" only from a team field visit (tools/import_field.mjs): public access and a 1–5 score.
const isVerified = f => f && f.access === "public" && f.condition != null;
const VISITED = {
  ro: d => `Verificat pe teren la ${d}.`,
  en: d => `Field-verified on ${d}.`,
  hu: d => `Helyszínen ellenőrizve: ${d}.` // TODO: HU review
};
function desc(c) {
  if (!isVerified(c.field)) return c.description;
  const out = {};
  for (const l of ["ro", "en", "hu"]) {
    const base = c.description[l].replace(/\s*\((OpenStreetMap|OpenStreetMap,)[^)]*\)\.?$/, ".");
    const extra = [c.field.issues].filter(Boolean).join(" ");
    out[l] = `${base} ${VISITED[l](c.field.visited_on)}${extra && l === "ro" ? " " + extra : ""}`;
  }
  return out;
}

const rows = data.courts.map(c => {
  const f = c.field, ok = isVerified(f), d = desc(c);
  return "  " + JSON.stringify({
    id: c.id, city: "sibiu", name: c.name, address: c.address, lat: c.lat, lng: c.lng,
    status: ok ? "verified" : "unverified", condition: ok ? f.condition : null, occupancy: "unknown", progress: 0, reports: 0,
    neighbourhood: c.neighbourhood, category: c.category, accessibility: c.accessibility,
    description: d.ro, desc: d, osm: c.sources.osm.value,
    img: ok && f.photos.length ? f.photos[0] : c.img,
    ...(f ? { field: { visitedOn: f.visited_on, access: f.access, condition: f.condition, photos: f.photos } } : {})
  });
});
const nVerified = data.courts.filter(c => isVerified(c.field)).length;
const block = `// Generated by tools/enrich_sibiu.mjs + tools/inject_sibiu.mjs — Data © OpenStreetMap contributors (ODbL). ${nVerified} of ${data.courts.length} field-verified.\n`
  + "const COURTS_SIBIU = [\n" + rows.join(",\n") + "\n];";

const re = /(\/\/ Generated by tools\/enrich_sibiu[^\n]*\n)?const COURTS_SIBIU = \[[\s\S]*?\n\];/;
if (!re.test(html)) throw new Error("COURTS_SIBIU block not found");
html = html.replace(re, () => block);

const hoods = JSON.stringify(data.neighbourhoods);
const cfgRe = /(sibiu: \{ nameRo:"Sibiu", nameEn:"Sibiu \/ Hermannstadt", nameHu:"Nagyszeben", center:\[[^\]]+\], zoom:\d+)(, hoods:\{[^}]*\})? \}/;
if (!cfgRe.test(html)) throw new Error("CITY_CFG.sibiu not found");
html = html.replace(cfgRe, (m, head) => `${head}, hoods:${hoods} }`);

writeFileSync(file, html);
console.log("injected", data.courts.length, "courts,", Object.keys(data.neighbourhoods).length, "hoods");
